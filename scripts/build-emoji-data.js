// Regenerates src/lib/emoji-data.js from the emojibase-data package.
// Run via `make emoji-data`; the output is committed so the extension loads without a build.
const fs = require("node:fs");
const path = require("node:path");
const data = require("emojibase-data/en/data.json");
const messages = require("emojibase-data/en/messages.json");

// Newer emoji render as empty boxes on systems whose fonts lag behind Unicode.
const MAX_EMOJI_VERSION = 15.1;
const GROUP_ICONS = {
  "smileys-emotion": "😀",
  "people-body": "👋",
  "animals-nature": "🐻",
  "food-drink": "🍔",
  "travel-places": "🚗",
  activities: "⚽",
  objects: "💡",
  symbols: "❤️",
  flags: "🏁"
};

const groups = messages.groups
  .filter(({ key }) => key in GROUP_ICONS)
  .map(({ key, message, order }) => ({
    label: message,
    icon: GROUP_ICONS[key],
    entries: data
      .filter((e) => e.group === order && e.version <= MAX_EMOJI_VERSION)
      .sort((a, b) => a.order - b.order)
      .map((e) => ({
        emoji: e.emoji,
        label: e.label,
        keywords: [e.label, ...(e.tags ?? [])].join(" ").toLowerCase()
      }))
  }));

const source = `(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) {
    module.exports = api;
  } else {
    root.EmojiFavicon = Object.assign(root.EmojiFavicon || {}, api);
  }
})(globalThis, function () {
  // GENERATED by scripts/build-emoji-data.js from emojibase-data (MIT). Do not edit.
  const emojiGroups = ${JSON.stringify(groups)};
  const emojiEntries = emojiGroups.flatMap((group) => group.entries);
  return { emojiGroups, emojiEntries };
});
`;
fs.writeFileSync(path.join(__dirname, "../src/lib/emoji-data.js"), source);
console.log(`${groups.map((g) => `${g.label}: ${g.entries.length}`).join("\n")}`);
